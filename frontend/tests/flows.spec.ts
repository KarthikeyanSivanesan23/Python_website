const password = 'Browser-flow-Password-529!'
async function signup(page: Page) {
  const username = `learner_${Date.now()}_${Math.floor(Math.random() * 1000)}`
  await page.goto('/auth')
  await page.getByLabel('Username', { exact: true }).fill(username)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Create my account' }).click()
  await expect(page.getByRole('heading', { name: `Welcome back, ${username}.` })).toBeVisible()
  return username
}
async function simpleEditor(page: Page) {
  await expect(page.locator('.editor-toolbar')).toBeVisible()
  const toggle = page.getByRole('button', { name: 'Use simple editor' })
  if (await toggle.isVisible()) await toggle.click()
  return page.getByRole('textbox', { name: 'Python code editor', exact: true })
}
