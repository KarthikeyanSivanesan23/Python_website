test('all 24 reference solutions, lesson examples and virtual-file isolation run in real Pyodide', async ({ page }) => {
  test.setTimeout(180000)
  await signup(page)
  const session = await (await page.request.get('/api/session/')).json()
  const chapters = await (await page.request.get('/api/curriculum/')).json()
  await page.evaluate(async () => {
    const path = '/src/features/editor/runtime.ts'
    const module = await import(path)
    ;(window as any).verificationRuntime = new module.PythonRuntime(() => {})
  })
  for (const chapter of chapters) {
    const lesson = await (await page.request.get(`/api/lessons/${chapter.id}/`)).json()
    const solution = await (await page.request.post(`/api/exercises/${lesson.exercise.id}/reveal/solution/`, { headers: { 'X-CSRFToken': session.csrfToken }, data: {} })).json()
    const result = await page.evaluate(async ({ code, tests }) => (window as any).verificationRuntime.run(code, [], tests), { code: solution.solution, tests: lesson.exercise.tests })
    expect(result.stderr, chapter.id).toBe('')
    expect(result.results.every((r: any) => r.status === 'passed'), `${chapter.id}: ${JSON.stringify(result.results)}`).toBeTruthy()
    const example = await page.evaluate(async ({ code, stdin }) => (window as any).verificationRuntime.run(code, stdin), { code: lesson.content.example, stdin: chapter.id === 'input-output' ? ['Ada'] : [] })
    expect(example.stdout, `${chapter.id} example`).toBe(lesson.content.expected_output)
    expect(example.stderr, `${chapter.id} example`).toBe('')
    for (const extra of lesson.content.extra_examples || []) {
      const result = await page.evaluate(async (code) => (window as any).verificationRuntime.run(code, []), extra.code)
      expect(result.stdout).toBe(extra.expected_output)
    }
  }
  const isolation = await page.evaluate(async () => {
    const runtime = (window as any).verificationRuntime
    const code = 'import os\nexisted = os.path.exists("leak.txt")\nwith open("leak.txt", "w") as f:\n    f.write("private")'
    const result = await runtime.run(code, [], [{ name: 'case one', expression: 'existed', expected: false, stdin: [] }, { name: 'case two', expression: 'existed', expected: false, stdin: [] }])
    const next = await runtime.run('import os\nprint(os.path.exists("leak.txt"))', [])
    runtime.dispose()
    return { result, next }
  })
  expect(isolation.result.results.every((r: any) => r.status === 'passed')).toBeTruthy()
  expect(isolation.next.stdout).toBe('False\n')
})
